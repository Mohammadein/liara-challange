"""
نرمال‌سازی متن فارسی — مشترک بین build time و زمان اجرا.

بدون این، «فايل» عربی و «فایل» فارسی برای BM25 دو کلمه‌ی کاملاً متفاوت‌اند و
جستجوی کلیدواژه‌ای روی نیمی از سؤالات کاربران شکست می‌خورد. کاربر ایرانی
هر دو شکل را تایپ می‌کند.
"""

from __future__ import annotations

import re

# ی و ک عربی → فارسی، و چند شکل دیگر
_CHAR_MAP = str.maketrans({
    "ي": "ی", "ﻱ": "ی", "ﻲ": "ی", "ی": "ی",
    "ك": "ک", "ﻙ": "ک", "ﻚ": "ک",
    "ۀ": "ه", "ة": "ه",
    "ؤ": "و", "إ": "ا", "أ": "ا", "آ": "ا", "ٱ": "ا",
    "‌": " ",   # نیم‌فاصله → فاصله
    "‏": " ", "‎": " ",
    "ـ": "",         # کشیدگی
})

# اعراب و علائم
_DIACRITICS = re.compile(r"[ً-ٰٟۖ-ۭ]")

# ارقام فارسی و عربی → لاتین
_DIGITS = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")

_PUNCT = re.compile(r"[^\w؀-ۿ]+")


def normalize(text: str) -> str:
    text = text.translate(_CHAR_MAP)
    text = _DIACRITICS.sub("", text)
    text = text.translate(_DIGITS)
    return re.sub(r"\s+", " ", text).strip().lower()


def tokenize(text: str) -> list[str]:
    """
    توکن‌سازی برای BM25.

    کلمات یک‌حرفی و حروف ربط پرتکرار حذف می‌شوند چون در هر سندی هستند و
    فقط نویز اضافه می‌کنند.
    """
    tokens = [t for t in _PUNCT.split(normalize(text)) if len(t) > 1]
    return [t for t in tokens if t not in STOPWORDS]


STOPWORDS = {
    "از", "به", "با", "در", "را", "که", "این", "آن", "برای", "تا", "بر",
    "است", "بود", "شد", "شده", "می", "های", "ها", "یک", "هم", "نیز",
    "خود", "کنید", "کند", "کنند", "باید", "بایست", "بایستی", "دهید",
    "اگر", "یا", "و", "اما", "پس", "چون", "طور", "مورد", "صورت", "عنوان",
    # کلمات پرسشی — هم در سؤال کاربر هستند هم در عنوان مستندات، پس هیچ
    # قدرت تفکیکی ندارند. بدون حذفشان «X چیست» به هر عنوانی که «چیست»
    # دارد وصل می‌شود، مستقل از موضوع.
    "چیست", "چیه", "چطور", "چگونه", "کجا", "چرا", "آیا", "کدام", "چند",
    "چه", "کنم", "بسازم", "دارد", "دارید", "شود", "شوند", "کردن", "انجام",
    "what", "how", "why", "where", "which", "when", "does", "did", "is",
    "the", "and", "for", "you", "your", "with", "this", "that", "from",
    "can", "will", "are", "not", "but", "have", "has",
}
